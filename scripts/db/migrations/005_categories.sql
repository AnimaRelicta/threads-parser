-- Допустимые переходы review_status (профиль, не ветка). Остальные запрещены на уровне БД.
-- review_failed -> pending_review нужен для повторной попытки по неудачным профилям.
CREATE FUNCTION check_review_status_transition() RETURNS trigger AS $$
BEGIN
    IF NEW.review_status = OLD.review_status THEN
        RETURN NEW;
    END IF;
    IF (OLD.review_status, NEW.review_status) IN (
        ('new', 'pending_review'),
        ('pending_review', 'reviewed'),
        ('pending_review', 'review_failed'),
        ('reviewed', 'pending_review'),
        ('review_failed', 'pending_review')
    ) THEN
        RETURN NEW;
    END IF;
    RAISE EXCEPTION 'profiles.review_status: переход % -> % запрещён (профиль %)',
        OLD.review_status, NEW.review_status, OLD.username;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER profiles_review_status_transition
    BEFORE UPDATE OF review_status ON profiles
    FOR EACH ROW EXECUTE FUNCTION check_review_status_transition();
